BEGIN;

CREATE TABLE IF NOT EXISTS public.words (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id TEXT NOT NULL DEFAULT gen_random_uuid()::text,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid(),
    word TEXT NOT NULL,
    transcription TEXT NOT NULL DEFAULT '',
    rusа TEXT NOT NULL,
    next_repeat TIMESTAMPTZ,
    is_priority BOOLEAN NOT NULL DEFAULT FALSE,
    priority_countdown INTEGER NOT NULL DEFAULT 0,
    priority_due_counter INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.words ADD COLUMN IF NOT EXISTS user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE;
ALTER TABLE public.words ADD COLUMN IF NOT EXISTS entry_id TEXT;
UPDATE public.words SET entry_id = id::text WHERE entry_id IS NULL;
ALTER TABLE public.words ALTER COLUMN entry_id SET DEFAULT gen_random_uuid()::text;
ALTER TABLE public.words ALTER COLUMN entry_id SET NOT NULL;
ALTER TABLE public.words ALTER COLUMN user_id SET DEFAULT auth.uid();
SELECT setval(pg_get_serial_sequence('public.words', 'id'),
    GREATEST((SELECT COALESCE(MAX(id), 0) FROM public.words), 1),
    EXISTS (SELECT 1 FROM public.words));
CREATE UNIQUE INDEX IF NOT EXISTS words_owner_entry_idx ON public.words (user_id, entry_id);
CREATE INDEX IF NOT EXISTS words_owner_repeat_idx ON public.words (user_id, next_repeat);

CREATE TABLE IF NOT EXISTS public.app_state (
    key TEXT PRIMARY KEY,
    value JSONB NOT NULL,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.app_state ADD COLUMN IF NOT EXISTS user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE;
ALTER TABLE public.app_state ALTER COLUMN user_id SET DEFAULT auth.uid();
UPDATE public.app_state SET key = 'cursor:' || user_id::text WHERE key = 'cursor' AND user_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS app_state_owner_key_idx ON public.app_state (key, user_id);

ALTER TABLE public.words ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.app_state ENABLE ROW LEVEL SECURITY;

DO $$
DECLARE item RECORD;
BEGIN
    FOR item IN SELECT tablename, policyname FROM pg_policies
        WHERE schemaname = 'public' AND tablename IN ('words', 'app_state')
    LOOP
        EXECUTE format('DROP POLICY %I ON public.%I', item.policyname, item.tablename);
    END LOOP;
END $$;

REVOKE ALL ON TABLE public.words, public.app_state FROM PUBLIC, anon, authenticated;
GRANT USAGE ON SCHEMA public TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.words, public.app_state TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.words_id_seq TO authenticated;
REVOKE ALL ON SEQUENCE public.words_id_seq FROM PUBLIC, anon;

CREATE POLICY words_select_own ON public.words FOR SELECT TO authenticated
    USING (user_id = (SELECT auth.uid()));
CREATE POLICY words_insert_own ON public.words FOR INSERT TO authenticated
    WITH CHECK (user_id = (SELECT auth.uid()));
CREATE POLICY words_update_own ON public.words FOR UPDATE TO authenticated
    USING (user_id = (SELECT auth.uid())) WITH CHECK (user_id = (SELECT auth.uid()));
CREATE POLICY words_delete_own ON public.words FOR DELETE TO authenticated
    USING (user_id = (SELECT auth.uid()));

CREATE POLICY app_state_select_own ON public.app_state FOR SELECT TO authenticated
    USING (user_id = (SELECT auth.uid()));
CREATE POLICY app_state_insert_own ON public.app_state FOR INSERT TO authenticated
    WITH CHECK (user_id = (SELECT auth.uid()));
CREATE POLICY app_state_update_own ON public.app_state FOR UPDATE TO authenticated
    USING (user_id = (SELECT auth.uid())) WITH CHECK (user_id = (SELECT auth.uid()));
CREATE POLICY app_state_delete_own ON public.app_state FOR DELETE TO authenticated
    USING (user_id = (SELECT auth.uid()));

COMMIT;
