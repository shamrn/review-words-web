import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';

const alice = '11111111-1111-4111-8111-111111111111';
const bob = '22222222-2222-4222-8222-222222222222';
const schema = await readFile(new URL('../schema.sql', import.meta.url), 'utf8');

async function createDatabase(legacy = false) {
  const db = new PGlite();
  await db.exec(`
    CREATE SCHEMA auth;
    CREATE ROLE anon;
    CREATE ROLE authenticated;
    CREATE TABLE auth.users (id UUID PRIMARY KEY);
    CREATE FUNCTION auth.uid() RETURNS UUID LANGUAGE SQL STABLE AS
      $$ SELECT nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
    GRANT USAGE ON SCHEMA auth TO anon, authenticated;
    INSERT INTO auth.users VALUES ('${alice}'), ('${bob}');
  `);
  if (legacy) {
    await db.exec(`
      CREATE TABLE public.words (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        word TEXT NOT NULL, transcription TEXT DEFAULT '', rus TEXT NOT NULL,
        next_repeat TIMESTAMPTZ, is_priority BOOLEAN DEFAULT FALSE,
        priority_countdown INTEGER DEFAULT 0, priority_due_counter INTEGER,
        created_at TIMESTAMPTZ DEFAULT NOW(), updated_at TIMESTAMPTZ DEFAULT NOW()
      );
      INSERT INTO public.words (id, word, rus) VALUES (5000, 'legacy', 'старое');
      ALTER TABLE public.words ENABLE ROW LEVEL SECURITY;
      CREATE POLICY "Allow public full access to words" ON public.words FOR ALL USING (true) WITH CHECK (true);
      GRANT ALL ON public.words TO anon, authenticated;
      CREATE TABLE public.app_state (key TEXT PRIMARY KEY, value JSONB NOT NULL, updated_at TIMESTAMPTZ DEFAULT NOW());
      INSERT INTO public.app_state VALUES ('cursor', '0', NOW());
    `);
  }
  if (legacy === 'owned') {
    await db.exec(`
      ALTER TABLE words ADD COLUMN user_id UUID REFERENCES auth.users(id);
      UPDATE words SET user_id='${alice}';
      ALTER TABLE app_state ADD COLUMN user_id UUID REFERENCES auth.users(id);
      UPDATE app_state SET user_id='${alice}';
      ALTER TABLE app_state DROP CONSTRAINT app_state_pkey;
      ALTER TABLE app_state ADD PRIMARY KEY(key,user_id);
    `);
  }
  await db.exec(schema);
  await db.exec(schema);
  await db.query(`INSERT INTO public.words (entry_id,user_id,word,rus) VALUES ('same',$1,'Alice private','a'),('same',$2,'Bob private','b')`, [alice, bob]);
  return db;
}

async function asRole(db, role, userId, action) {
  await db.exec('BEGIN');
  try {
    await db.exec(`SET LOCAL ROLE ${role}`);
    await db.query("SELECT set_config('request.jwt.claim.sub', $1, true)", [userId || '']);
    return await action();
  } finally {
    await db.exec('ROLLBACK');
  }
}

for (const legacy of [false, true, 'owned']) {
  test(`SQL migration and RLS enforce ownership (${legacy === 'owned' ? 'existing account data' : legacy ? 'existing tables' : 'fresh database'})`, async () => {
    const db = await createDatabase(legacy);
    try {
      const query = (sql, args) => db.query(sql, args);
      assert.equal((await query("SELECT count(*)::int AS n FROM pg_policies WHERE tablename IN ('words','app_state')")).rows[0].n, 8);
      if (legacy) assert.equal((await query("SELECT count(*)::int AS n FROM words WHERE word='legacy'")).rows[0].n, 1);
      await assert.rejects(asRole(db, 'anon', null, () => query('SELECT * FROM words')), /permission denied/);
      await assert.rejects(asRole(db, 'anon', null, () => query("INSERT INTO words(word,rus) VALUES ('x','y')")), /permission denied/);
      await assert.rejects(asRole(db, 'authenticated', alice, () => query('TRUNCATE words')), /permission denied/);
      assert.equal((await asRole(db, 'authenticated', null, () => query('SELECT * FROM words'))).rows.length, 0);
      const visible = await asRole(db, 'authenticated', alice, () => query("SELECT word FROM words WHERE entry_id='same'"));
      assert.deepEqual(visible.rows.map((row) => row.word), ['Alice private']);
      await assert.rejects(asRole(db, 'authenticated', alice, () => query("INSERT INTO words(entry_id,user_id,word,rus) VALUES ('spoof',$1,'x','y')", [bob])), /row-level security/);
      await assert.rejects(asRole(db, 'authenticated', alice, () => query('UPDATE words SET user_id=$1 WHERE user_id=$2', [bob, alice])), /row-level security/);
      const update = await asRole(db, 'authenticated', alice, () => query("UPDATE words SET word='stolen' WHERE user_id=$1 RETURNING word", [bob]));
      assert.equal(update.rows.length, 0);
      const deletion = await asRole(db, 'authenticated', alice, () => query('DELETE FROM words WHERE user_id=$1 RETURNING word', [bob]));
      assert.equal(deletion.rows.length, 0);
      await asRole(db, 'authenticated', alice, async () => {
        const result = await query("INSERT INTO words(entry_id,word,rus) VALUES ('new','own','свой') RETURNING user_id", []);
        assert.equal(result.rows[0].user_id, alice);
        await query("INSERT INTO words(entry_id,user_id,word,rus) VALUES ('new',$1,'updated','свой') ON CONFLICT(user_id,entry_id) DO UPDATE SET word=EXCLUDED.word", [alice]);
        assert.equal((await query("SELECT word FROM words WHERE entry_id='new'")).rows[0].word, 'updated');
        assert.equal((await query("DELETE FROM words WHERE entry_id='new' RETURNING word")).rows.length, 1);
        await query("INSERT INTO app_state(key,user_id,value) VALUES ($1,$2,'42') ON CONFLICT(key,user_id) DO UPDATE SET value=EXCLUDED.value", [`cursor:${alice}`, alice]);
        assert.equal((await query('SELECT value FROM app_state')).rows[0].value, 42);
      });
      await assert.rejects(asRole(db, 'authenticated', alice, () => query("INSERT INTO app_state(key,user_id,value) VALUES ('spoof',$1,'0')", [bob])), /row-level security/);
    } finally {
      await db.close();
    }
  });
}
